export type CategoryType = { name: string; text: string };
export type QA = { q: string; a: string };

/** A reference table on the category page (sizes, how to read a code). rows[0] is the header row. */
export type SizeTable = { title: string; note: string; rows: string[][] };

/** "a | b | c" lines → rows, and back. The admin panel edits a table as text. */
export const parseTable = (text: string) =>
  text
    .split("\n")
    .map((line) => line.split("|").map((cell) => cell.trim()))
    .filter((cells) => cells.some(Boolean));
export const tableText = (rows: string[][]) => rows.map((r) => r.join(" | ")).join("\n");

export type Category = {
  /** Link: /products/<slug>. Never changes after the category is created. */
  slug: string;
  name: string;
  icon: IconName;
  /** One line on the category card. */
  short: string;
  /** "الإجابة باختصار": the first paragraph of the page (what AI answers quote). */
  answer: string;
  types: CategoryType[];
  /** Example part numbers / series, shown as tags. */
  codes: string[];
  faq: QA[];
  /** Optional reference table. Missing in data saved before it existed. */
  table?: SizeTable;
  /** Uploaded photo (/uploads/…) or "" for the icon. */
  image: string;
  visible: boolean;
  seoTitle?: string;
  seoDescription?: string;
};

